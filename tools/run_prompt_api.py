#!/usr/bin/env python3
"""Optional OpenAI Responses API runner for a build_prompt.py packet."""
import argparse
from datetime import datetime
from zoneinfo import ZoneInfo
import getpass
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
MODEL = 'gpt-6.1-sol'


def strict_schema(schema):
    """Prepare a separate strict API schema without editing the frozen file."""
    result = {k: v for k, v in schema.items() if k != '$schema'}
    if result.get('type') == 'object':
        result['properties'] = {k: strict_schema(v) for k, v in result['properties'].items()}
        result['required'] = list(result['properties'])
        result['additionalProperties'] = False
    if 'items' in result:
        result['items'] = strict_schema(result['items'])
    return result


def response_json(response):
    if response.get('status') != 'completed':
        raise ValueError('API response was not completed; increase --max-output-tokens if truncated.')
    chunks = []
    for item in response.get('output', []):
        if item.get('type') != 'message':
            continue
        for content in item.get('content', []):
            if content.get('type') == 'refusal':
                raise ValueError('The model refused the request; no response file was written.')
            if content.get('type') == 'output_text':
                chunks.append(content['text'])
    data = json.loads(''.join(chunks))
    if not isinstance(data, dict):
        raise ValueError('Expected a JSON object.')
    return data


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prompt', required=True, type=Path, help='Packet generated by build_prompt.py')
    parser.add_argument('--env-file', type=Path, help='Explicit .env path; defaults to the repository .env')
    parser.add_argument('--max-output-tokens', type=int, default=8000)
    parser.add_argument('--dry-run', action='store_true', help='Check inputs without a key, API call, or output file')
    args = parser.parse_args(argv)
    # Match the originating agent when using build_prompt.py's standard packet name.
    packet_name = args.prompt.stem
    agent_names = sorted((ROOT / 'agents').iterdir(), key=lambda p: len(p.name), reverse=True)
    agent = next((p for p in agent_names if p.is_dir() and packet_name.startswith(p.name + '_')), None)
    response_dir = agent / 'responses' if agent else ROOT / 'work' / 'api_responses'
    stamp = datetime.now(ZoneInfo('America/New_York')).strftime('%Y-%m-%d_%H-%M-%S_%f%z')
    args.out = response_dir / f'{packet_name}_response_{stamp}.json'
    env_file = args.env_file if args.env_file is not None else ROOT / '.env'
    if args.env_file is not None and not env_file.is_file():
        parser.error('The specified --env-file does not exist.')
    if env_file.is_file():
        try:
            from dotenv import dotenv_values
        except ImportError:
            parser.error('Install python-dotenv in the runner environment to load .env files.')
        # Read supported settings only; inherited environment takes precedence.
        settings = dotenv_values(env_file)
        for name in ('OPEN_AI_API_KEY', 'OPENAI_API_KEY'):
            if not os.environ.get(name) and settings.get(name):
                os.environ[name] = settings[name]
    if args.max_output_tokens <= 0:
        parser.error('--max-output-tokens must be positive')
    if args.out.exists():
        parser.error('Output already exists; choose a new --out path to preserve earlier results.')
    prompt = args.prompt.read_text(encoding='utf-8')
    if not prompt.strip():
        parser.error('Prompt packet is empty.')
    schema = json.loads((ROOT / 'core/output_schema.json').read_text())
    payload = {
        'model': MODEL,
        'input': prompt,
        'store': False,
        'max_output_tokens': args.max_output_tokens,
        'text': {'format': {'type': 'json_schema', 'name': 'specialist_response',
                            'strict': True, 'schema': strict_schema(schema)}},
    }
    payload['tools'] = [{'type': 'web_search'}]
    if args.dry_run:
        print('Inputs checked. No API request made; model availability is not verified.')
        return 0
    key = (os.environ.get('OPEN_AI_API_KEY') or os.environ.get('OPENAI_API_KEY', '')).strip()
    if not key:
        if not sys.stdin.isatty():
            parser.error('Set OPEN_AI_API_KEY or OPENAI_API_KEY in your environment/.env, use --env-file, or run interactively.')
        key = getpass.getpass('OpenAI API key (hidden; not saved): ').strip()
    if not key:
        parser.error('API key is empty.')
    try:
        from openai import OpenAI, APIStatusError, APIConnectionError, APITimeoutError
    except ImportError:
        print('Install the SDK: python3 -m pip install -r tools/requirements-api.txt', file=sys.stderr)
        return 1
    try:
        # No automatic retries that could duplicate billable work.
        with OpenAI(api_key=key, timeout=300.0, max_retries=0) as client:
            result = client.responses.create(**payload)
            response = result.model_dump(mode='json')
    except APIStatusError as error:
        hints = {401: 'Check the API key.', 403: 'Check project/model permissions.',
                 429: 'Check API quota/billing or rate limits.',
                 400: 'Check model support for structured outputs and web search.'}
        print(f'API HTTP {error.status_code}. {hints.get(error.status_code, "Check OpenAI API status and request settings.")}', file=sys.stderr)
        return 1
    except (APITimeoutError, APIConnectionError):
        print('Network request failed or timed out. Completion and billing may be uncertain; no automatic retry.', file=sys.stderr)
        return 1
    data = response_json(response)
    # Validate before writing the requested output. A failed candidate is preserved separately.
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', suffix='.json', encoding='utf-8', delete=False) as tmp:
        json.dump(data, tmp, indent=2, ensure_ascii=False)
        tmp.write('\n')
        candidate = Path(tmp.name)
    try:
        validation = subprocess.run([sys.executable, str(ROOT / 'tools/validate_response.py'), str(candidate)],
                                    capture_output=True, text=True)
        if validation.returncode:
            failed = args.out.with_name(args.out.stem + '.invalid.json')
            with failed.open('x', encoding='utf-8') as handle:
                handle.write(candidate.read_text())
            print(validation.stdout or validation.stderr, file=sys.stderr)
            print(f'Invalid candidate preserved: {failed}', file=sys.stderr)
            return 1
        with args.out.open('x', encoding='utf-8') as handle:
            handle.write(candidate.read_text())
    finally:
        candidate.unlink(missing_ok=True)
    print('VALIDATION PASSED')
    print(f'Saved OpenAI API response: {args.out}')
    print(f'Model: {response.get("model", MODEL)}; response ID: {response.get("id", "unknown")}')
    if response.get('usage'):
        print('Token usage: ' + json.dumps(response['usage']))
    print('This is an API run, not a ChatGPT UI run. Review sources and findings separately.')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, ValueError, EOFError) as error:
        print(f'Error: {error}', file=sys.stderr)
        sys.exit(1)
